"""Shared vocabulary / normalisation helpers for the TW-AMR Watch data pipeline.

All code lists live in data/curated/dims/*.json (human-editable). This module
loads them and resolves names printed in the PDFs / transcription CSVs to the
canonical codes used in public/data/*.json.
"""
from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DIMS_DIR = ROOT / "data" / "curated" / "dims"

PRECISION_RANK = {"table": 3, "text": 2, "chart_estimate": 1}
READ_METHOD_TO_PRECISION = {
    "table": "table",
    "text": "text", "narrative": "text", "caption": "text", "label": "text", "data_label": "text",
    "bar_estimate": "chart_estimate", "line_estimate": "chart_estimate", "chart_estimate": "chart_estimate",
    "chart": "chart_estimate", "estimate": "chart_estimate", "point_estimate": "chart_estimate",
}
SKIP_READ_METHODS = {"unreadable", "missing", "na", "n/a"}


def _key(s: str) -> str:
    """Case/space/punctuation-insensitive matching key."""
    s = (s or "").strip().lower()
    s = s.replace("–", "-").replace("—", "-").replace("　", " ")
    s = re.sub(r"\s+", " ", s)
    return s.rstrip(".")


def load_json(name: str) -> dict:
    return json.loads((DIMS_DIR / name).read_text(encoding="utf-8"))


class Vocab:
    def __init__(self) -> None:
        common = load_json("common.json")
        self.levels = common["levels"]
        self.wards = common["wards"]
        self.settings = common["settings"]
        self.specimens = common["specimens"]
        self.precisions = common["precisions"]
        self.organisms = load_json("organisms.json")["organisms"]
        abx = load_json("antibiotics.json")
        self.antibiotics = abx["antibiotics"]
        self.antibiotic_groups = abx["groups"]
        self.phenotypes = load_json("phenotypes.json")["phenotypes"]

        self.org_by_code = {o["code"]: o for o in self.organisms}
        self.abx_by_code = {a["code"]: a for a in self.antibiotics}
        self.pheno_by_code = {p["code"]: p for p in self.phenotypes}

        self._org = {}
        for o in self.organisms:
            for n in [o["code"], o["name"]["en"], *o["meta"].get("aliases", [])]:
                self._org.setdefault(_key(n), o["code"])
        self._abx_abbr = {}
        self._abx_name = {}
        for a in self.antibiotics:
            for ab in a["meta"].get("thas", []):
                self._abx_abbr[ab.upper()] = a["code"]
            for n in [a["name"]["en"], *a["meta"].get("aliases", [])]:
                self._abx_name.setdefault(_key(n), a["code"])
        self._pheno = {}
        for p in self.phenotypes:
            for n in [p["code"], *p["meta"].get("aliases", [])]:
                self._pheno[_key(n)] = p["code"]
        self._simple = {}
        for dimname in ("levels", "settings", "specimens", "wards"):
            m = {}
            for d in getattr(self, dimname):
                for n in [d["code"], d["name"]["en"], d["name"]["zh-TW"], *d.get("meta", {}).get("aliases", [])]:
                    m[_key(n)] = d["code"]
            self._simple[dimname] = m
        # auto-generated codes for names not in the vocabulary (reported as warnings)
        self.auto_organisms: dict[str, dict] = {}
        self.auto_antibiotics: dict[str, dict] = {}

    # --- organisms -------------------------------------------------------
    def organism(self, name: str, warn=None) -> str | None:
        if not name or not name.strip():
            return None
        k = _key(name)
        if k in self._org:
            return self._org[k]
        k2 = _key(re.sub(r"\(.*?\)", "", name))
        if k2 in self._org:
            return self._org[k2]
        code = "X-" + re.sub(r"[^A-Z0-9]+", "-", name.upper()).strip("-")[:28]
        if code not in self.auto_organisms:
            self.auto_organisms[code] = {"code": code, "name": {"zh-TW": name.strip(), "en": name.strip(), "ja": name.strip()},
                                         "group": "unmapped", "order": 900 + len(self.auto_organisms),
                                         "meta": {"autoGenerated": True, "printedName": name.strip()}}
            if warn:
                warn(f"unknown organism {name!r} -> auto code {code} (add it to data/curated/dims/organisms.json)")
        self._org[k] = code
        return code

    # --- antibiotics -----------------------------------------------------
    def antibiotic(self, abbr: str | None, name: str | None = None, warn=None) -> str | None:
        if abbr and abbr.strip():
            a = abbr.strip().upper().replace(" ", "")
            if a in self._abx_abbr:
                return self._abx_abbr[a]
        if name and name.strip():
            k = _key(name)
            if k in self._abx_name:
                return self._abx_name[k]
            k2 = _key(re.sub(r"\(.*?\)", "", name))
            if k2 in self._abx_name:
                return self._abx_name[k2]
            for inner in re.findall(r"\((.*?)\)", name):
                if inner.strip().upper() in self._abx_abbr:
                    return self._abx_abbr[inner.strip().upper()]
                if _key(inner) in self._abx_name:
                    return self._abx_name[_key(inner)]
            if name.strip().upper() in self._abx_abbr:
                return self._abx_abbr[name.strip().upper()]
        label = (abbr or name or "").strip()
        if not label:
            return None
        code = "X-" + re.sub(r"[^A-Z0-9]+", "-", label.upper()).strip("-")[:28]
        if code not in self.auto_antibiotics:
            self.auto_antibiotics[code] = {"code": code, "name": {"zh-TW": (name or label).strip(), "en": (name or label).strip(), "ja": (name or label).strip()},
                                           "group": "unmapped", "order": 900 + len(self.auto_antibiotics),
                                           "meta": {"autoGenerated": True, "printed": label}}
            if warn:
                warn(f"unknown antibiotic abbr={abbr!r} name={name!r} -> auto code {code} (add it to data/curated/dims/antibiotics.json)")
        return code

    def phenotype(self, name: str) -> str | None:
        return self._pheno.get(_key(name))

    def simple(self, dimname: str, value: str | None, default: str | None = None) -> str | None:
        if value is None or not str(value).strip():
            return default
        return self._simple[dimname].get(_key(str(value)))


@lru_cache(maxsize=1)
def vocab() -> Vocab:
    return Vocab()


def precision_from_read_method(m: str | None) -> str | None:
    """Map a transcription `read_method` to the contract `precision`; None = skip row."""
    k = _key(m or "")
    if k in SKIP_READ_METHODS:
        return None
    if not k:
        return "chart_estimate"
    return READ_METHOD_TO_PRECISION.get(k, "chart_estimate")


def to_float(s) -> float | None:
    if s is None:
        return None
    s = str(s).strip().replace(",", "").replace("%", "")
    if not s or s.lower() in {"na", "n/a", "-", "—", "nan"}:
        return None
    try:
        return float(s)
    except ValueError:
        return None


def to_int(s) -> int | None:
    f = to_float(s)
    return None if f is None else int(round(f))
